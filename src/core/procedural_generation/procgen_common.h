/**
 * procgen_common.h
 * Shared pure C++26 Procedural Generation primitives (`src/core/procedural_generation/`).
 *
 * ============================================================================
 * ARCHITECTURAL PLAN & DESIGN NOTES (THREE-PILLAR PROCEDURAL ARCHITECTURE)
 * ============================================================================
 * 1. NAMING CONVENTION:
 *    - Redundant `ProcGen` prefixes are dropped across new types in `IdeamProceduralGeneration`.
 *    - Where semantic specificity is needed, descriptive names are used:
 *        * `AnalysisRule` & `AnalysisStyle`: Govern how a source pattern is analyzed.
 *        * `GenerationRule`: A single rule generated by analyzing a source pattern (or authored).
 *        * `ProceduralPattern`: A managed, cascading collection of `GenerationRule`s output by
 *          a `ProceduralPatterner`.
 *        * `ProceduralPatterner`: Evaluates an `AnalysisStyle` over a Godot source artifact
 *          (`PackedScene`, `Node` hierarchy, `Resource`, `RefCounted`) to emit a `ProceduralPattern`.
 *        * `ProceduralEnvironment`: The unified Godot-reflection-bounded environment upon which
 *          `ProceduralPattern`, `IdeamWaveFunctionCollapse`, and `IdeamQuantumDarwinism` operate.
 *
 * 2. PILLAR 1 — CSS-STYLE CASCADING ANALYSIS & GENERATION RULES:
 *    - Parallels `GameplayRule` and `GameplayStyle` in `IdeamGames`.
 *    - Both `AnalysisRule` and `GenerationRule` operate on a cascading, tag-and-type-matched
 *      specificity system (`CascadeLayer`, `RuleScope`, `priority`, `is_important`, `specificity`).
 *
 * 3. PILLAR 2 — UNIFIED GODOT-REFLECTION-BOUNDED ENVIRONMENT:
 *    - All procedural algorithms (`IdeamProceduralGeneration`, `IdeamWaveFunctionCollapse`,
 *      `IdeamQuantumDarwinism`, and future pattern solvers) define and mutate the same
 *      `ProceduralEnvironment`, bounded by Godot's reflection capabilities (`ClassDB`,
 *      `SceneState`, node hierarchies, names, `RID`s, properties, value ranges, methods, signals).
 *
 * 4. PILLAR 3 — TASKGRAPH-FIRST SYNERGY (`IdeamTasks` / `TaskGraphDOD`):
 *    - Pattern analysis, rule cascade compilation, forward WFC solving, and Quantum Darwinism
 *      einselection conflict repair are decomposed into 64-byte cache-aligned TaskGraph nodes
 *      that share contiguous DOD buffers.
 */

