/**
 * Synchronization directions supported by NarrativeResourceCommitTransformLogic (N11),
 * mirroring GameEntitySnapshotSyncTransformLogic (G11) in IdeamGames.
 */
enum NarrativeCommitSyncMode : uint8_t {
    NARRATIVE_SYNC_COMMIT_TO_GODOT     = 0, // Commits dirty DOD state to NarrativeTelemetrySnapshotPOD & queues story signals
    NARRATIVE_SYNC_PULL_FROM_GODOT     = 1, // Pulls live authoring / OOP NarrativeTelemetrySnapshotPOD state into DOD buffers
    NARRATIVE_SYNC_BUILD_SNAPSHOT_ONLY = 2  // Builds NarrativeTelemetrySnapshotPOD without consuming transition flags
};

/**
 * Story signal type codes queued into NarrativeSignalCommandPOD for main-thread Godot Resource::emit_signal().
 */
enum NarrativeStorySignalType : uint8_t {
    STORY_SIGNAL_NONE                  = 0,
    STORY_SIGNAL_INCIDENT_HAPPENED     = 1,  // Incident "happened"
    STORY_SIGNAL_INCIDENT_CANNOT_HAPPEN= 2,  // Incident "cannot_happen"
    STORY_SIGNAL_PLOT_BEGUN            = 3,  // Plot "begun"
    STORY_SIGNAL_PLOT_COMPLETED        = 4,  // Plot "completed"
    STORY_SIGNAL_PLOT_CANNOT_COMPLETE  = 5,  // Plot "cannot_complete"
    STORY_SIGNAL_PLOT_FAILED           = 6,  // Plot "failed"
    STORY_SIGNAL_CONDITION_MET         = 7,  // Incident_Condition "met"
    STORY_SIGNAL_CONDITION_UNMET       = 8,  // Incident_Condition "unmet"
    STORY_SIGNAL_CONDITION_CANNOT_MEET = 9,  // Incident_Condition "cannot_meet"
    STORY_SIGNAL_CONDITION_UNKNOWN     = 10, // Gameplay_Condition "became_unknown"
    STORY_SIGNAL_ROLE_FILLED           = 11, // Narrative "role_filled" / "symbol_filled" / "place_filled" / "moment_filled" / "story_filled"
    STORY_SIGNAL_ROLE_VACATED          = 12, // Narrative "role_vacated" / "symbol_vacated" / "place_vacated" / "moment_vacated" / "story_vacated"
    STORY_SIGNAL_LOCATION_ENTERED      = 13, // Character/Prop "location_entered" & Location "character_entered"/"prop_entered"
    STORY_SIGNAL_LOCATION_EXITED       = 14, // Character/Prop "location_exited"  & Location "character_exited"/"prop_exited"
    STORY_SIGNAL_PROP_TAKEN            = 15, // Prop "taken" & Character "possession_taken"
    STORY_SIGNAL_PROP_RELEASED         = 16, // Prop "released" & Character "possession_lost"
    STORY_SIGNAL_PROP_LOST             = 17, // Prop "became_lost"
    STORY_SIGNAL_PROP_FOUND            = 18  // Prop "found"
};

/**
 * NarrativeSignalCommandPOD (16-Byte Aligned)
 * Deferred main-thread signal dispatch record generated by NarrativeResourceCommitTransformLogic (N11).
 */
struct alignas(16) NarrativeSignalCommandPOD {
    uint32_t source_id       = INVALID_ID;        // 4B: Source Narreme / Condition / Symbolic slot ID
    uint32_t related_id      = INVALID_ID;        // 4B: Companion Narreme ID (e.g. assigned literal, entered location, possessor)
    int32_t status_payload   = 0;                 // 4B: Resolved status value (IncidentStatus, PlotStatus, NarremeConditionStatus)
    uint8_t signal_type      = STORY_SIGNAL_NONE; // 1B: NarrativeStorySignalType
    uint8_t narreme_type     = NARREME_TYPE_ANY;  // 1B: NarremeType of source_id
    uint16_t reserved        = 0u;                // 2B -> Total = 16B
};

static_assert(sizeof(NarrativeSignalCommandPOD) == 16, "NarrativeSignalCommandPOD must be 16 bytes!");

/**
 * NarrativeTelemetrySnapshotPOD (32-Byte Aligned)
 * Pointer-free boundary snapshot row synchronizing MemoryManagerDOD columns with Godot Narrative / Narreme resources.
 */
struct alignas(32) NarrativeTelemetrySnapshotPOD {
    uint32_t narreme_id           = INVALID_ID;                      // 4B: Row ID in NarremeIdentityAndTraitBuffer
    uint32_t location_id          = INVALID_ID;                      // 4B: Current Location ID
    uint32_t possessor_id         = INVALID_ID;                      // 4B: Current Possessor Character ID
    int32_t assigned_literal_id   = -1;                              // 4B: Assigned Literal ID (if Symbolic slot)
    int32_t fit_score             = NARRATIVE_MAX_DISCREPANCY_SCORE; // 4B: Symbolic assignment fit score
    int8_t incident_status        = INCIDENT_STATUS_HAS_NOT_HAPPENED;// 1B: IncidentStatusDOD
    int8_t plot_status            = PLOT_STATUS_NOT_BEGUN;           // 1B: PlotStatusDOD
    int8_t condition_status       = COND_STATUS_UNKNOWN;             // 1B: NarremeConditionStatusDOD
    uint8_t narreme_type          = NARREME_TYPE_CHARACTER;          // 1B: NarremeType
    uint8_t dirty_mask            = 0u;                              // 1B: Bitmask of dirty channels this frame
    bool valid                    = false;                           // 1B: True when populated
    uint8_t reserved_pad[6]       = {0};                             // 6B -> Total = 32B
};

static_assert(sizeof(NarrativeTelemetrySnapshotPOD) == 32, "NarrativeTelemetrySnapshotPOD must be 32 bytes!");

